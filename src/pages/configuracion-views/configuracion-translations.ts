export function getConfiguracionCopy(language: Language) {
  return copy[language];
}

export function getEnglishDay(day: string) {
  const days: Readonly<Record<string, string>> = {
    Lunes: 'Monday',
    Martes: 'Tuesday',
    Miércoles: 'Wednesday',
    Jueves: 'Thursday',
    Viernes: 'Friday',
    Sábado: 'Saturday',
    Domingo: 'Sunday',
  };
  return days[day] ?? day;
}

export function formatRouteDay(day: string, language: Language) {
  return language === 'en' ? getEnglishDay(day) : day;
}

export function localizeTabulatorFallback(value: string, language: Language) {
  if (language === 'es') return value;
  return (
    (
      {
        'Sin área': 'No area',
        'Sin puesto': 'No position',
        'Sin tipo': 'No type',
      } as const
    )[value as 'Sin área' | 'Sin puesto' | 'Sin tipo'] ?? value
  );
}

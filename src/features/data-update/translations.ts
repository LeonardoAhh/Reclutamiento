export function dataUpdateText(language: Language, spanishText: string): string {
  if (language !== "en") return spanishText;
  const directTranslation = englishCopy.get(spanishText);
  if (directTranslation) return directTranslation;

  const requiredField = /^(.+) es obligatorio\.$/.exec(spanishText);
  if (requiredField) {
    const field = englishCopy.get(requiredField[1]) ?? requiredField[1];
    return `${field} is required.`;
  }

  const searchNoMatch = /^No hay coincidencias para “(.+)”\.$/.exec(spanishText);
  if (searchNoMatch) return `No matches for “${searchNoMatch[1]}”.`;

  const childRemoval = /^Se eliminará la fecha de nacimiento del hijo (\d+)\.$/.exec(spanishText);
  if (childRemoval) return `The date of birth for child ${childRemoval[1]} will be deleted.`;

  const openWhatsApp = /^Abrir WhatsApp de (.+) en una pestaña nueva$/.exec(spanishText);
  if (openWhatsApp) return `Open WhatsApp for ${openWhatsApp[1]} in a new tab`;

  const downloadContact = /^Descargar contacto de (.+)$/.exec(spanishText);
  if (downloadContact) return `Download contact for ${downloadContact[1]}`;

  const duplicateShift = /^el número (.+) está duplicado\.$/.exec(spanishText);
  if (duplicateShift) return `employee number ${duplicateShift[1]} is duplicated.`;

  const missingShiftEmployee = /^el número (.+) no existe en esta campaña\.$/.exec(spanishText);
  if (missingShiftEmployee) return `employee number ${missingShiftEmployee[1]} does not exist in this campaign.`;

  const multipleBirthDates = /^Se eliminarán (\d+) fechas de nacimiento ya capturadas\.$/.exec(spanishText);
  if (multipleBirthDates) return `${multipleBirthDates[1]} entered dates of birth will be deleted.`;

  const rowPrefix = /^Fila (\d+): (.+)$/.exec(spanishText);
  if (rowPrefix) {
    const detail = englishCopy.get(rowPrefix[2]) ?? rowPrefix[2];
    const missingColumns = /^faltan columnas: (.+)\.$/.exec(rowPrefix[2]);
    const duplicateEmployee = /^número de empleado duplicado (.+)\.$/.exec(rowPrefix[2]);
    const duplicateShiftEmployee = /^el número (.+) está duplicado\.$/.exec(rowPrefix[2]);
    const missingShiftEmployee = /^el número (.+) no existe en esta campaña\.$/.exec(rowPrefix[2]);
    if (missingColumns) return `Row ${rowPrefix[1]}: missing columns: ${missingColumns[1]}.`;
    if (duplicateEmployee) return `Row ${rowPrefix[1]}: duplicate employee number ${duplicateEmployee[1]}.`;
    if (duplicateShiftEmployee) return `Row ${rowPrefix[1]}: employee number ${duplicateShiftEmployee[1]} is duplicated.`;
    if (missingShiftEmployee) return `Row ${rowPrefix[1]}: employee number ${missingShiftEmployee[1]} does not exist in this campaign.`;
    return `Row ${rowPrefix[1]}: ${detail}`;
  }

  const employeeNumber = /^Empleado (.+)$/.exec(spanishText);
  if (employeeNumber) return `Employee ${employeeNumber[1]}`;

  const photoAlt = /^Fotografía de (.+)$/.exec(spanishText);
  if (photoAlt) return `Photo of ${photoAlt[1]}`;

  const previewAlt = /^Vista previa de (.+), pendiente de guardar$/.exec(spanishText);
  if (previewAlt) return `Preview of ${previewAlt[1]}, not yet saved`;

  return spanishText;
}

export function useDataUpdateText() {
  const { language } = useLanguage();
  return useCallback(
    (spanishText: string, englishOverride?: string) => (
      language === "en" && englishOverride
        ? englishOverride
        : dataUpdateText(language, spanishText)
    ),
    [language],
  );
}
